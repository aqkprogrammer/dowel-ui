/** WCAG 2.2 AA: normal text. */
const TEXT_MINIMUM = 4.5;
/** WCAG 2.2 AA: large text, and non-text UI such as borders and focus rings. */
const UI_MINIMUM = 3;

interface Pair {
  label: string;
  foreground: string;
  background: string;
  minimum: number;
  /**
   * Advisory pairs are reported but do not fail.
   *
   * WCAG 1.4.11 covers what is needed to *identify* a component or its state.
   * A divider or a card outline is structural decoration — the content inside
   * is already distinguishable without it — so holding those to 3:1 would mean
   * heavy rules everywhere in the name of a rule that does not apply. An input
   * border is different: the field's background matches the page, so the border
   * is the only thing saying it is a field.
   */
  advisory?: boolean;
}

