/**
 * WCAG contrast audit of the design tokens.
 *
 * Automated accessibility testing cannot check colour contrast in a test
 * environment that never paints, so this checks the palette at the source
 * instead: every semantic pair, in light and dark, across every theme preset.
 *
 *   pnpm audit:contrast
 */
